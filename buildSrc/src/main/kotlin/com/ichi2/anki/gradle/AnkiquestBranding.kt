package com.ichi2.anki.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Upstream's visible strings that name AnkiDroid, saying AnkiQuest instead. The overrides are
 * made from upstream's own files at build time, so upstream's wording changes and translations
 * reach them without copies that could conflict with an upstream merge.
 */
object AnkiquestBranding {
    const val UPSTREAM_NAME = "AnkiDroid"
    const val NAME = "AnkiQuest"

    /** The file written into each `values*` directory of the generated resources. */
    const val FILE = "ankiquest_branding.xml"

    private val COMMENT = Regex("<!--.*?-->", RegexOption.DOT_MATCHES_ALL)

    /** A `<string>` or `<plurals>` element with its name; self-closing (empty) strings never match. */
    private val ELEMENT =
        Regex("""<(string|plurals)\s[^>]*?name="([^"]+)"[^>]*(?<!/)>.*?</\1>""", RegexOption.DOT_MATCHES_ALL)
    private const val UNTRANSLATABLE = """translatable="false""""

    /** The resource names in a keep list: one per line, `#` starts a comment. */
    fun keepList(text: String): Set<String> =
        text
            .lineSequence()
            .map { it.substringBefore('#').trim() }
            .filter { it.isNotEmpty() }
            .toSet()

    /**
     * The `<string>` and `<plurals>` elements of a values file whose text names AnkiDroid, saying
     * AnkiQuest. Only elements named in [names] count, if given; untranslatable strings never do.
     * Attributes stay as they are.
     */
    fun rebrand(
        xml: String,
        names: Set<String>? = null,
    ): List<Pair<String, String>> =
        ELEMENT
            .findAll(COMMENT.replace(xml, ""))
            .mapNotNull { match ->
                val element = match.value
                val name = match.groupValues[2]
                val open = element.substring(0, element.indexOf('>') + 1)
                val text = element.substring(open.length)
                when {
                    names != null && name !in names -> null
                    UNTRANSLATABLE in open -> null
                    UPSTREAM_NAME !in text -> null
                    else -> name to open + text.replace(UPSTREAM_NAME, NAME)
                }
            }.toList()

    /**
     * The names to rebrand: strings whose default (English) text names AnkiDroid, except [keep].
     * A translation that names AnkiDroid where the English text does not is left as upstream has it.
     */
    fun names(
        defaults: List<String>,
        keep: Set<String>,
    ): Set<String> =
        defaults
            .flatMap { rebrand(it) }
            .map { it.first }
            .filter { it !in keep }
            .toSet()

    /** A values file holding [elements]. */
    fun file(elements: List<String>): String =
        buildString {
            append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
            append("<!-- Generated by the ankiquestBranding task from upstream's strings; do not edit. -->\n")
            append("<resources xmlns:tools=\"http://schemas.android.com/tools\" ")
            append("tools:ignore=\"ExtraTranslation,MissingTranslation,UnusedResources,DuplicateCrowdInStrings\">\n")
            elements.forEach { append("    ").append(it).append('\n') }
            append("</resources>\n")
        }

    /** Writes the overrides for every `values*` directory under [upstream] into [output]. */
    fun generate(
        upstream: File,
        keep: Set<String>,
        output: File,
    ) {
        output.deleteRecursively()

        fun xmlFiles(directory: File) = directory.listFiles { file -> file.extension == "xml" }.orEmpty().sortedBy { it.name }
        val names = names(xmlFiles(File(upstream, "values")).map { it.readText() }, keep)

        // Every locale upstream ships, and the default.
        val directories = upstream.listFiles { file -> file.isDirectory && file.name.startsWith("values") }.orEmpty()
        for (directory in directories.sortedBy { it.name }) {
            val elements = xmlFiles(directory).flatMap { rebrand(it.readText(), names) }.map { it.second }
            if (elements.isEmpty()) {
                continue
            }

            val target = File(output, "${directory.name}/$FILE")
            target.parentFile.mkdirs()
            target.writeText(file(elements))
        }
    }
}

/** Generates the [AnkiquestBranding] overrides as a resource directory. */
@CacheableTask
abstract class AnkiquestBrandingTask : DefaultTask() {
    /** Upstream's resources: `common/android/src/main/res`. */
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val upstreamRes: DirectoryProperty

    /** The names that keep saying AnkiDroid. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val keepFile: RegularFileProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        AnkiquestBranding.generate(
            upstreamRes.get().asFile,
            AnkiquestBranding.keepList(keepFile.get().asFile.readText()),
            output.get().asFile,
        )
    }
}
